"""RUN records: one Markdown file per relevant execution, plus ``docs/runs/INDEX.md``.

Records are generated by code from what the run actually produced; humans only append
observations. A run from a dirty tree is marked NÃO REPRODUTÍVEL.
"""

import subprocess
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any

from src.config import PROJECT_ROOT

RUNS_DIR = PROJECT_ROOT / "docs" / "runs"
INDEX = RUNS_DIR / "INDEX.md"


def _git(*args: str) -> str:
    out = subprocess.run(["git", *args], cwd=PROJECT_ROOT, capture_output=True, check=False)
    return out.stdout.decode("utf-8", errors="replace").strip()


def git_state() -> tuple[str, bool]:
    """Current commit SHA and whether tracked files have uncommitted changes."""
    return _git("rev-parse", "HEAD"), bool(_git("status", "--porcelain", "--untracked-files=no"))


def next_run_id(kind: str, scenario: str, day: str | None = None) -> str:
    """``RUN-<YYYYMMDD>-<kind>-<scenario>-<nn>`` with the next free sequence number."""
    day = day or datetime.now().strftime("%Y%m%d")
    prefix = f"RUN-{day}-{kind}-{scenario}-"
    taken = [int(p.stem[len(prefix) :]) for p in RUNS_DIR.glob(f"{prefix}*.md")]
    return f"{prefix}{max(taken, default=0) + 1:02d}"


@dataclass
class RunRecord:
    """Everything a RUN record states. Numbers come from the run, never typed by hand."""

    run_id: str
    kind: str
    scenario: str
    seed: int
    data_hash: str
    model: str
    mlflow_ref: str
    metrics: dict[str, dict[str, float]]
    verdict: str
    artifacts: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    extra: dict[str, Any] = field(default_factory=dict)
    sha: str = ""
    dirty: bool = False
    created: str = field(default_factory=lambda: datetime.now().strftime("%Y-%m-%d %H:%M"))


def _metrics_table(metrics: dict[str, dict[str, float]]) -> str:
    sets = list(metrics)
    names = sorted({m for values in metrics.values() for m in values})
    head = "| Métrica | " + " | ".join(sets) + " |\n|---|" + "---|" * len(sets)
    rows = [f"| {n} | " + " | ".join(_fmt(metrics[s].get(n)) for s in sets) + " |" for n in names]
    return "\n".join([head, *rows])


def _fmt(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:.4f}"
    return "—" if value is None else str(value)


def render(rec: RunRecord) -> str:
    """Markdown body of a RUN record."""
    repro = "não — NÃO REPRODUTÍVEL" if rec.dirty else "sim"
    lines = [
        f"# {rec.run_id}\n",
        "> Gerado por `src/reporting/run_record.py`. Não editar números à mão.\n",
        "| Campo | Valor |", "|---|---|", f"| Data | {rec.created} |", f"| Tipo | {rec.kind} |",
        f"| Git SHA | `{rec.sha}` |", f"| Árvore limpa | {repro} |",
        f"| Hash dos dados de entrada | `{rec.data_hash}` |",
        f"| Cenário / seed | {rec.scenario} / {rec.seed} |", f"| Modelo | {rec.model} |",
        f"| MLflow | {rec.mlflow_ref} |",
        *[f"| {k} | {_fmt(v)} |" for k, v in rec.extra.items()],
        "\n## Métricas\n", _metrics_table(rec.metrics), "\n## Artefatos\n",
        *[f"- `{a}`" for a in rec.artifacts], f"\n## Veredito\n\n{rec.verdict}\n",
        "## Observações\n", *[f"- {n}" for n in rec.notes], "",
    ]  # fmt: skip
    return "\n".join(lines)


def write_record(rec: RunRecord) -> Path:
    """Write the record and append its line to the index."""
    rec.sha, rec.dirty = git_state()
    path = RUNS_DIR / f"{rec.run_id}.md"
    path.write_text(render(rec), encoding="utf-8")
    repro = "não" if rec.dirty else "sim"
    line = (f"| [{rec.run_id}]({path.name}) | {rec.created[:10]} | {rec.kind} | "
            f"{rec.scenario} | {rec.verdict.splitlines()[0]} | {repro} |\n")  # fmt: skip
    with INDEX.open("a", encoding="utf-8") as fh:
        fh.write(line)
    return path
