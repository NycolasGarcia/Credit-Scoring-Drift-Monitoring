"""Grafana dashboard as code: ``monitoring/grafana/dashboards/cdm_monitoring.json``.

Generated by ``make alerts``; a test keeps the committed JSON in sync with this module.
"""

import json
from typing import Any

from src.config import PROJECT_ROOT

DASHBOARD_PATH = PROJECT_ROOT / "monitoring" / "grafana" / "dashboards" / "cdm_monitoring.json"
DS = {"type": "prometheus", "uid": "cdm-prom"}
SEL = 'scenario=~"$scenario"'
SEV_COLORS = [{"color": "green", "value": None}, {"color": "yellow", "value": 1},
              {"color": "orange", "value": 2}, {"color": "red", "value": 3}]  # fmt: skip
STEP_MAP = [{"type": "value", "options": {
    "1": {"text": "ok", "color": "green"}, "0": {"text": "falhou", "color": "red"},
    "-1": {"text": "pulada", "color": "gray"}}}]  # fmt: skip


def _target(expr: str, legend: str = "", ref: str = "A", instant: bool = False) -> dict[str, Any]:
    t = {"datasource": DS, "expr": expr, "legendFormat": legend, "refId": ref}
    if instant:  # current value only: label-valued stats would list every series in the range
        t |= {"instant": True, "range": False}
    return t


def panel(title: str, kind: str, grid: tuple[int, int, int, int], targets: list[dict],
          **cfg: Any) -> dict[str, Any]:  # fmt: skip
    """One panel; ``cfg`` may carry ``defaults``, ``overrides``, ``options``, ``description``."""
    x, y, w, h = grid
    return {"title": title, "type": kind, "datasource": DS, "targets": targets,
            "gridPos": {"x": x, "y": y, "w": w, "h": h}, "description": cfg.get("description", ""),
            "fieldConfig": {"defaults": cfg.get("defaults", {}),
                            "overrides": cfg.get("overrides", [])},
            "options": cfg.get("options", {})}  # fmt: skip


def severity_overrides() -> list[dict[str, Any]]:
    """Color each alert series by the severity in its name."""
    colors = {"SEV-1": "yellow", "SEV-2": "orange", "SEV-3": "red"}
    return [{"matcher": {"id": "byRegexp", "options": f".*{sev}.*"},
             "properties": [{"id": "color", "value": {"mode": "fixed", "fixedColor": c}}]}
            for sev, c in colors.items()]  # fmt: skip


def _thresholds(steps: list[dict[str, Any]]) -> dict[str, Any]:
    return {"thresholds": {"mode": "absolute", "steps": steps}, "color": {"mode": "thresholds"}}


def header_panels() -> list[dict[str, Any]]:
    """Top row: batch, month, severity, diagnosis, time since last success."""
    sev = {**_thresholds(SEV_COLORS), "min": 0, "max": 3}
    return [
        panel("Lote", "stat", (0, 0, 4, 4), [_target(f"cdm_batch_index{{{SEL}}}")]),
        panel("Mês do lote", "stat", (4, 0, 5, 4),
              [_target(f"cdm_batch_info{{{SEL}}}", "{{issue_month}}", instant=True)],
              options={"textMode": "name", "colorMode": "none", "text": {"valueSize": 34}}),
        panel("Severidade do lote", "stat", (9, 0, 5, 4), [_target(f"cdm_batch_severity{{{SEL}}}")],
              defaults=sev),
        panel("Diagnóstico", "stat", (14, 0, 5, 4),
              [_target(f"cdm_diagnosis{{{SEL}}} == 1", "{{code}}", instant=True)],
              options={"textMode": "name", "colorMode": "none", "text": {"valueSize": 34}}),
        panel("Segundos desde o último lote concluído", "stat", (19, 0, 5, 4),
              [_target(f"time() - max(cdm_last_success_timestamp_seconds{{{SEL}}})")],
              defaults={**_thresholds([{"color": "green", "value": None},
                                       {"color": "red", "value": 30}]), "unit": "s"}),
    ]  # fmt: skip


def body_panels() -> list[dict[str, Any]]:
    """Pipeline health, volume, drift, output, labeled performance, severity, alerts."""
    hist = {"showValue": "never", "rowHeight": 0.9}
    psi = {**_thresholds([{"color": "green", "value": None}, {"color": "yellow", "value": 0.1},
                          {"color": "red", "value": 0.25}]), "decimals": 3}  # fmt: skip
    return [
        panel("Saúde do pipeline (status por etapa)", "status-history", (0, 4, 12, 7),
              [_target(f"cdm_step_status{{{SEL}}}", "{{step}}")],
              defaults={"mappings": STEP_MAP},
              options={**hist, "legend": {"showLegend": False}}),
        panel("Duração por etapa", "timeseries", (12, 4, 12, 7),
              [_target(f"cdm_step_duration_seconds{{{SEL}}}", "{{step}}")],
              defaults={"unit": "s",
                        "custom": {"stacking": {"mode": "normal"}, "fillOpacity": 30}}),
        panel("Volume e quarentena", "timeseries", (0, 11, 12, 7),
              [_target(f"cdm_batch_rows{{{SEL}}}", "{{stage}}"),
               _target(f"cdm_gate_blocked{{{SEL}}}", "lote bloqueado", "B")]),
        panel("Score e aprovação", "timeseries", (12, 11, 12, 7),
              [_target(f"cdm_score_psi{{{SEL}}}", "PSI do score"),
               _target(f"cdm_approval_rate{{{SEL}}}", "taxa de aprovação", "B"),
               _target(f"cdm_expected_bad_rate{{{SEL}}}", "bad rate esperado", "C")]),
        panel("PSI por feature e lote", "status-history", (0, 18, 24, 14),
              [_target(f"cdm_feature_psi{{{SEL}}}", "{{feature}}")], defaults=psi,
              options={"showValue": "never", "rowHeight": 0.95},
              description="Bins fixos da referência; amarelo ≥ 0,10 (SEV-1), vermelho ≥ 0,25."),
        panel("Desempenho com rótulo maduro", "timeseries", (0, 32, 12, 7),
              [_target(f"cdm_bad_rate_ratio{{{SEL}}}", "observado / esperado"),
               _target(f"cdm_auc_mature{{{SEL}}}", "AUC madura", "B")],
              defaults={"custom": {"drawStyle": "points", "pointSize": 8}}),
        panel("Severidade por sinal", "status-history", (12, 32, 12, 7),
              [_target(f"cdm_signal_severity{{{SEL}}}", "{{signal}}")],
              defaults={**_thresholds(SEV_COLORS), "min": 0, "max": 3}, options=hist),
        panel("Alertas disparados (Prometheus)", "state-timeline", (0, 39, 24, 8),
              [_target("max by (scenario, alertname, severity) "
                       f'(ALERTS{{alertstate="firing",{SEL}}})',
                       "{{scenario}} {{alertname}} {{severity}}")],
              defaults={"mappings": [{"type": "value", "options": {"1": {"text": "disparado"}}}],
                        "color": {"mode": "fixed", "fixedColor": "red"}},
              overrides=severity_overrides(),
              options={"showValue": "never", "mergeValues": True},
              description="Inclui o dead man's switch (sem rótulo de cenário: o monitor é um só)."),
        panel("Resposta: decisões do lote", "timeseries", (0, 47, 16, 8),
              [_target(f"cdm_decisions{{{SEL}}}", "{{decision}}")],
              defaults={"custom": {"stacking": {"mode": "normal"}, "fillOpacity": 40}},
              description="approve, review (faixa cinza, kill switch ou quarentena) e reject."),
        panel("Resposta: modo conservador e risco", "timeseries", (16, 47, 8, 8),
              [_target(f"cdm_conservative_mode{{{SEL}}}", "modo conservador"),
               _target(f"cdm_expected_bad_rate_approved{{{SEL}}}", "bad rate aprovados", "B"),
               _target(f"cdm_kill_switch{{{SEL}}}", "kill switch", "C")]),
    ]  # fmt: skip


def dashboard() -> dict[str, Any]:
    """Whole dashboard model."""
    panels = [*header_panels(), *body_panels()]
    for i, p in enumerate(panels, start=1):
        p["id"] = i
    variable = {"name": "scenario", "type": "query", "datasource": DS, "refresh": 2,
                "query": {"query": "label_values(cdm_batch_index, scenario)", "refId": "V"},
                "includeAll": True, "allValue": ".*", "multi": False, "current": {}}  # fmt: skip
    return {"uid": "cdm-monitoring", "title": "Credit Scoring — saúde do modelo e dos dados",
            "tags": ["cdm"], "timezone": "browser", "schemaVersion": 41, "version": 1,
            "refresh": "5s", "time": {"from": "now-20m", "to": "now"},
            "templating": {"list": [variable]}, "panels": panels}  # fmt: skip


def render() -> str:
    """Dashboard JSON text."""
    return json.dumps(dashboard(), indent=2, ensure_ascii=False) + "\n"


def main() -> None:
    """Write the dashboard file."""
    DASHBOARD_PATH.parent.mkdir(parents=True, exist_ok=True)
    DASHBOARD_PATH.write_text(render(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
